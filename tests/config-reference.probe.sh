#!/usr/bin/env bash
# tests/config-reference.probe.sh — hermetic probe for tests/config-reference.py
# and live check of plugins/seyag/config/knobs.tsv + docs/config.md.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$REPO_ROOT/tests/config-reference.py"

FAILURES=0
ok()   { echo "ok: $1"; }
fail() { echo "FAIL: $1"; FAILURES=$((FAILURES + 1)); }

echo "=== config-reference probe ==="

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

mkdir -p \
  "$TMP/plugins/seyag/hooks" \
  "$TMP/plugins/seyag/bin" \
  "$TMP/plugins/seyag/skills/demo" \
  "$TMP/plugins/seyag/config"

cat >"$TMP/plugins/seyag/hooks/sample.sh" <<'EOF'
#!/usr/bin/env bash
alpha="${SYG_ALPHA:-1}"
bravo="${SYG_BRAVO:-}"
charlie="${SYG_CHARLIE:-}"
EOF

cat >"$TMP/plugins/seyag/bin/sample-tool" <<'EOF'
#!/usr/bin/env python3
import os
a = os.environ.get("SYG_ALPHA", "1")
d = os.environ.get("SYG_DELTA", "60")
e = os.environ.get("CLAUDE_USAGE_ECHO", "75")
p = os.environ.get("CLAUDE_PROJECTS_DIR", "~/.claude/projects")
EOF

# Excluded files: .md and *.probe.sh must not be scanned.
cat >"$TMP/plugins/seyag/skills/demo/SKILL.md" <<'EOF'
Prose mention of SYG_FOXTROT stays out of the scan.
EOF

cat >"$TMP/plugins/seyag/hooks/sample.probe.sh" <<'EOF'
#!/usr/bin/env bash
export SYG_GOLF=1
EOF

write_valid_tsv() {
  cat >"$TMP/plugins/seyag/config/knobs.tsv" <<'EOF'
# Format: name<TAB>scope<TAB>group<TAB>default<TAB>description
# Rule: every env name the scan finds has exactly one row; regenerate docs/config.md after any edit.
CLAUDE_PROJECTS_DIR	user	session	~/.claude/projects	Directory of per-project transcripts.
CLAUDE_USAGE_ECHO	user	usage	75	Echo reserve percentage (1-99).
SYG_ALPHA	user	guards	1	Controls alpha guard mode (0|1).
SYG_BRAVO	user	guards	unset	Opt-in bravo flag.
SYG_CHARLIE	internal	guards	unset	Internal charlie test seam.
SYG_DELTA	user	usage	60	Delta window in seconds.
EOF
}

write_valid_tsv

# (a) Happy path: --write generates docs/config.md, --check passes, exclusions and formatting hold.
if python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.a1"; then
  ok "(a1) --write succeeds on valid fixture"
else
  fail "(a1) --write failed on valid fixture: $(cat "$TMP/err.a1")"
fi

if [ -f "$TMP/docs/config.md" ]; then
  ok "(a2) --write created docs/config.md"
else
  fail "(a2) docs/config.md was not created"
fi

if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.a3"; then
  ok "(a3) --check passes immediately after --write"
else
  fail "(a3) --check failed after --write: $(cat "$TMP/err.a3")"
fi

if grep -q 'Generated by `tests/config-reference.py --write` from `plugins/seyag/config/knobs.tsv`; do not edit by hand' "$TMP/docs/config.md"; then
  ok "(a4) docs/config.md carries generator header"
else
  fail "(a4) docs/config.md missing generator header"
fi

if grep -F -q '| `SYG_ALPHA` | `1` | Controls alpha guard mode (0\|1). | `bin/sample-tool`, `hooks/sample.sh` |' "$TMP/docs/config.md"; then
  ok "(a5) SYG_ALPHA row escapes pipe and sorts multi-file readers"
else
  fail "(a5) SYG_ALPHA row formatting mismatch in docs/config.md"
fi

if grep -F -q '| `SYG_BRAVO` | unset | Opt-in bravo flag. | `hooks/sample.sh` |' "$TMP/docs/config.md"; then
  ok "(a6) unset default stays plain (un-backticked)"
else
  fail "(a6) SYG_BRAVO unset default formatting mismatch"
fi

if grep -F -q '| `SYG_CHARLIE` | `hooks/sample.sh` | Internal charlie test seam. |' "$TMP/docs/config.md"; then
  ok "(a7) internal row renders in Internal names table"
else
  fail "(a7) SYG_CHARLIE internal row missing or misformatted"
fi

if ! grep -qE 'SYG_FOXTROT|SYG_GOLF' "$TMP/docs/config.md"; then
  ok "(a8) .md and .probe.sh names excluded from scan"
else
  fail "(a8) excluded name leaked into docs/config.md"
fi

# (b) Undocumented name in code -> --check fails naming variable and reader file.
echo 'undoc="${SYG_UNDOCUMENTED:-}"' >>"$TMP/plugins/seyag/hooks/sample.sh"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.b"; then
  fail "(b) --check passed despite undocumented SYG_UNDOCUMENTED"
elif grep -q 'SYG_UNDOCUMENTED' "$TMP/err.b" && grep -q 'hooks/sample.sh' "$TMP/err.b"; then
  ok "(b) undocumented name in code fails --check naming SYG_UNDOCUMENTED and hooks/sample.sh"
else
  fail "(b) stderr did not name SYG_UNDOCUMENTED and hooks/sample.sh: $(cat "$TMP/err.b")"
fi
sed -i '/SYG_UNDOCUMENTED/d' "$TMP/plugins/seyag/hooks/sample.sh"

# (c) Stale row in knobs.tsv -> --check fails naming stale variable.
printf 'SYG_STALE_ROW\tuser\tguards\tunset\tStale row.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.c"; then
  fail "(c) --check passed despite stale row SYG_STALE_ROW"
elif grep -q 'SYG_STALE_ROW' "$TMP/err.c"; then
  ok "(c) stale row in knobs.tsv fails --check naming SYG_STALE_ROW"
else
  fail "(c) stderr did not name SYG_STALE_ROW: $(cat "$TMP/err.c")"
fi
write_valid_tsv

# (d) Hand-edited docs/config.md -> --check fails naming docs/config.md.
echo "<!-- hand edit -->" >>"$TMP/docs/config.md"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.d"; then
  fail "(d) --check passed despite hand-edited docs/config.md"
elif grep -q 'docs/config.md' "$TMP/err.d"; then
  ok "(d) hand-edited docs/config.md fails --check naming docs/config.md"
else
  fail "(d) stderr did not name docs/config.md: $(cat "$TMP/err.d")"
fi
python3 "$SCRIPT" --root "$TMP" --write

# (e) Bad scope and bad group in knobs.tsv -> --check fails naming offending value.
sed -i 's/SYG_ALPHA\tuser\tguards/SYG_ALPHA\tbogus_scope\tguards/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.e1"; then
  fail "(e1) --check passed despite invalid scope bogus_scope"
elif grep -q 'SYG_ALPHA' "$TMP/err.e1" && grep -q 'bogus_scope' "$TMP/err.e1"; then
  ok "(e1) invalid scope fails --check naming SYG_ALPHA and bogus_scope"
else
  fail "(e1) stderr did not name SYG_ALPHA and bogus_scope: $(cat "$TMP/err.e1")"
fi
write_valid_tsv

sed -i 's/SYG_ALPHA\tuser\tguards/SYG_ALPHA\tuser\tbogus_group/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.e2"; then
  fail "(e2) --check passed despite invalid group bogus_group"
elif grep -q 'SYG_ALPHA' "$TMP/err.e2" && grep -q 'bogus_group' "$TMP/err.e2"; then
  ok "(e2) invalid group fails --check naming SYG_ALPHA and bogus_group"
else
  fail "(e2) stderr did not name SYG_ALPHA and bogus_group: $(cat "$TMP/err.e2")"
fi
write_valid_tsv

# (f) Duplicate row in knobs.tsv -> --check fails naming duplicate variable.
printf 'SYG_ALPHA\tuser\tguards\t1\tDuplicate row.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.f"; then
  fail "(f) --check passed despite duplicate SYG_ALPHA row"
elif grep -q 'SYG_ALPHA' "$TMP/err.f" && grep -qi 'duplicate' "$TMP/err.f"; then
  ok "(f) duplicate row in knobs.tsv fails --check naming SYG_ALPHA"
else
  fail "(f) stderr did not name duplicate SYG_ALPHA: $(cat "$TMP/err.f")"
fi
write_valid_tsv

# Live check against the repository root.
if python3 "$SCRIPT" --root "$REPO_ROOT" --check 2>"$TMP/err.live"; then
  ok "(live) repo knobs.tsv and docs/config.md are valid and in sync"
else
  fail "(live) repo check failed: $(cat "$TMP/err.live")"
fi

echo ""
if [ "$FAILURES" -gt 0 ]; then
  echo "FAILED ($FAILURES failure(s))"
  exit 1
fi
echo "ALL PASSED"
exit 0
