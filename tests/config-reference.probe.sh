#!/usr/bin/env bash
# tests/config-reference.probe.sh — hermetic probe for tests/config-reference.py
# and live check of plugins/seyag/config/knobs.tsv + docs/config.md.

set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPT="$REPO_ROOT/tests/config-reference.py"

FAILURES=0
ok()   { echo "ok: $1"; }
fail() { echo "FAIL: $1"; FAILURES=$((FAILURES + 1)); }

echo "=== config-reference probe ==="

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

mkdir -p \
  "$TMP/plugins/seyag/hooks" \
  "$TMP/plugins/seyag/bin" \
  "$TMP/plugins/seyag/skills/demo" \
  "$TMP/plugins/seyag/config"

cat >"$TMP/plugins/seyag/hooks/sample.sh" <<'EOF'
#!/usr/bin/env bash
alpha="${SYG_ALPHA:-1}"
bravo="${SYG_BRAVO:-}"
charlie="${SYG_CHARLIE:-}"
EOF

cat >"$TMP/plugins/seyag/bin/sample-tool" <<'EOF'
#!/usr/bin/env python3
import os
a = os.environ.get("SYG_ALPHA", "1")
d = os.environ.get("SYG_DELTA", "60")
e = os.environ.get("CLAUDE_USAGE_ECHO", "75")
p = os.environ.get("CLAUDE_PROJECTS_DIR", "~/.claude/projects")
EOF

# Excluded files: .md and *.probe.sh must not be scanned.
cat >"$TMP/plugins/seyag/skills/demo/SKILL.md" <<'EOF'
Prose mention of SYG_FOXTROT stays out of the scan.
EOF

cat >"$TMP/plugins/seyag/hooks/sample.probe.sh" <<'EOF'
#!/usr/bin/env bash
export SYG_GOLF=1
EOF

write_valid_tsv() {
  cat >"$TMP/plugins/seyag/config/knobs.tsv" <<'EOF'
# Format: name<TAB>scope<TAB>group<TAB>default<TAB>description
# Rule: every env name the scan finds has exactly one row; regenerate docs/config.md after any edit.
CLAUDE_PROJECTS_DIR	user	session	~/.claude/projects	Directory of per-project transcripts.
CLAUDE_USAGE_ECHO	user	usage	75	Echo reserve percentage (1-99).
SYG_ALPHA	user	guards	1	Controls alpha guard mode (0|1).
SYG_BRAVO	user	guards	unset	Opt-in bravo flag.
SYG_CHARLIE	internal	guards	unset	Internal charlie test seam.
SYG_DELTA	user	usage	60	Delta window in seconds.
EOF
}

write_valid_tsv

# (a) Happy path: --write generates docs/config.md, --check passes, exclusions and formatting hold.
if python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.a1"; then
  ok "(a1) --write succeeds on valid fixture"
else
  fail "(a1) --write failed on valid fixture: $(cat "$TMP/err.a1")"
fi

if [ -f "$TMP/docs/config.md" ]; then
  ok "(a2) --write created docs/config.md"
else
  fail "(a2) docs/config.md was not created"
fi

if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.a3"; then
  ok "(a3) --check passes immediately after --write"
else
  fail "(a3) --check failed after --write: $(cat "$TMP/err.a3")"
fi

if grep -q 'Generated by `tests/config-reference.py --write` from `plugins/seyag/config/knobs.tsv`; do not edit by hand' "$TMP/docs/config.md"; then
  ok "(a4) docs/config.md carries generator header"
else
  fail "(a4) docs/config.md missing generator header"
fi

if grep -F -q '| `SYG_ALPHA` | `1` | Controls alpha guard mode (0\|1). | `bin/sample-tool`, `hooks/sample.sh` |' "$TMP/docs/config.md"; then
  ok "(a5) SYG_ALPHA row escapes pipe and sorts multi-file readers"
else
  fail "(a5) SYG_ALPHA row formatting mismatch in docs/config.md"
fi

if grep -F -q '| `SYG_BRAVO` | unset | Opt-in bravo flag. | `hooks/sample.sh` |' "$TMP/docs/config.md"; then
  ok "(a6) unset default stays plain (un-backticked)"
else
  fail "(a6) SYG_BRAVO unset default formatting mismatch"
fi

if grep -F -q '| `SYG_CHARLIE` | `hooks/sample.sh` | Internal charlie test seam. |' "$TMP/docs/config.md"; then
  ok "(a7) internal row renders in Internal names table"
else
  fail "(a7) SYG_CHARLIE internal row missing or misformatted"
fi

if ! grep -qE 'SYG_FOXTROT|SYG_GOLF' "$TMP/docs/config.md"; then
  ok "(a8) .md and .probe.sh names excluded from scan"
else
  fail "(a8) excluded name leaked into docs/config.md"
fi

# (b) Undocumented name in code -> --check fails naming variable and reader file.
echo 'undoc="${SYG_UNDOCUMENTED:-}"' >>"$TMP/plugins/seyag/hooks/sample.sh"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.b"; then
  fail "(b) --check passed despite undocumented SYG_UNDOCUMENTED"
elif grep -q 'SYG_UNDOCUMENTED' "$TMP/err.b" && grep -q 'hooks/sample.sh' "$TMP/err.b"; then
  ok "(b) undocumented name in code fails --check naming SYG_UNDOCUMENTED and hooks/sample.sh"
else
  fail "(b) stderr did not name SYG_UNDOCUMENTED and hooks/sample.sh: $(cat "$TMP/err.b")"
fi
sed -i '/SYG_UNDOCUMENTED/d' "$TMP/plugins/seyag/hooks/sample.sh"

# (c) Stale row in knobs.tsv -> --check fails naming stale variable.
printf 'SYG_STALE_ROW\tuser\tguards\tunset\tStale row.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.c"; then
  fail "(c) --check passed despite stale row SYG_STALE_ROW"
elif grep -q 'SYG_STALE_ROW' "$TMP/err.c"; then
  ok "(c) stale row in knobs.tsv fails --check naming SYG_STALE_ROW"
else
  fail "(c) stderr did not name SYG_STALE_ROW: $(cat "$TMP/err.c")"
fi
write_valid_tsv

# (d) Hand-edited docs/config.md -> --check fails naming docs/config.md.
echo "<!-- hand edit -->" >>"$TMP/docs/config.md"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.d"; then
  fail "(d) --check passed despite hand-edited docs/config.md"
elif grep -q 'docs/config.md' "$TMP/err.d"; then
  ok "(d) hand-edited docs/config.md fails --check naming docs/config.md"
else
  fail "(d) stderr did not name docs/config.md: $(cat "$TMP/err.d")"
fi
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.d.write"; then
  fail "(d) restoring docs/config.md with --write failed: $(cat "$TMP/err.d.write")"
fi

# (e) Bad scope and bad group in knobs.tsv -> --check fails naming offending value.
sed -i $'s/SYG_ALPHA\tuser\tguards/SYG_ALPHA\tbogus_scope\tguards/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.e1"; then
  fail "(e1) --check passed despite invalid scope bogus_scope"
elif grep -q 'SYG_ALPHA' "$TMP/err.e1" && grep -q 'bogus_scope' "$TMP/err.e1"; then
  ok "(e1) invalid scope fails --check naming SYG_ALPHA and bogus_scope"
else
  fail "(e1) stderr did not name SYG_ALPHA and bogus_scope: $(cat "$TMP/err.e1")"
fi
write_valid_tsv

sed -i $'s/SYG_ALPHA\tuser\tguards/SYG_ALPHA\tuser\tbogus_group/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.e2"; then
  fail "(e2) --check passed despite invalid group bogus_group"
elif grep -q 'SYG_ALPHA' "$TMP/err.e2" && grep -q 'bogus_group' "$TMP/err.e2"; then
  ok "(e2) invalid group fails --check naming SYG_ALPHA and bogus_group"
else
  fail "(e2) stderr did not name SYG_ALPHA and bogus_group: $(cat "$TMP/err.e2")"
fi
write_valid_tsv

# (f) Duplicate row in knobs.tsv -> --check fails naming duplicate variable.
printf 'SYG_ALPHA\tuser\tguards\t1\tDuplicate row.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.f"; then
  fail "(f) --check passed despite duplicate SYG_ALPHA row"
elif grep -q 'SYG_ALPHA' "$TMP/err.f" && grep -qi 'duplicate' "$TMP/err.f"; then
  ok "(f) duplicate row in knobs.tsv fails --check naming SYG_ALPHA"
else
  fail "(f) stderr did not name duplicate SYG_ALPHA: $(cat "$TMP/err.f")"
fi
write_valid_tsv

# (g) Bare $SYG_INDIA in a fixture file -> passes with a row, fails naming SYG_INDIA without it.
echo 'echo "$SYG_INDIA"' >>"$TMP/plugins/seyag/hooks/sample.sh"
printf 'SYG_INDIA\tuser\tguards\tunset\tBare variable reference.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.g.w"; then
  fail "(g) --write failed with bare \$SYG_INDIA row: $(cat "$TMP/err.g.w")"
elif ! python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.g.c1"; then
  fail "(g) --check failed with bare \$SYG_INDIA row: $(cat "$TMP/err.g.c1")"
else
  write_valid_tsv
  if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.g.c2"; then
    fail "(g) --check passed after removing SYG_INDIA row"
  elif grep -q 'SYG_INDIA' "$TMP/err.g.c2"; then
    ok "(g) bare \$SYG_INDIA passes --check with a row and fails naming SYG_INDIA without it"
  else
    fail "(g) stderr did not name SYG_INDIA: $(cat "$TMP/err.g.c2")"
  fi
fi
sed -i '/SYG_INDIA/d' "$TMP/plugins/seyag/hooks/sample.sh"
write_valid_tsv
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.g.restore"; then
  fail "(g) restoring docs/config.md with --write failed: $(cat "$TMP/err.g.restore")"
fi

# (h) awk ENVIRON["SYG_JULIET"] in a fixture file -> passes with a row, fails naming SYG_JULIET without it.
echo 'awk '\''BEGIN { print ENVIRON["SYG_JULIET"] }'\''' >>"$TMP/plugins/seyag/hooks/sample.sh"
printf 'SYG_JULIET\tuser\tguards\tunset\tAwk ENVIRON reference.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.h.w"; then
  fail "(h) --write failed with SYG_JULIET row: $(cat "$TMP/err.h.w")"
elif ! python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.h.c1"; then
  fail "(h) --check failed with SYG_JULIET row: $(cat "$TMP/err.h.c1")"
else
  write_valid_tsv
  if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.h.c2"; then
    fail "(h) --check passed after removing SYG_JULIET row"
  elif grep -q 'SYG_JULIET' "$TMP/err.h.c2"; then
    ok "(h) awk ENVIRON[\"SYG_JULIET\"] passes --check with a row and fails naming SYG_JULIET without it"
  else
    fail "(h) stderr did not name SYG_JULIET: $(cat "$TMP/err.h.c2")"
  fi
fi
sed -i '/SYG_JULIET/d' "$TMP/plugins/seyag/hooks/sample.sh"
write_valid_tsv
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.h.restore"; then
  fail "(h) restoring docs/config.md with --write failed: $(cat "$TMP/err.h.restore")"
fi

# (i) User row with an empty description -> --check fails.
sed -i $'s/^SYG_ALPHA\t.*/SYG_ALPHA\tuser\tguards\t1\t/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.i"; then
  fail "(i) --check passed despite empty description on SYG_ALPHA"
elif grep -q 'SYG_ALPHA' "$TMP/err.i" && grep -qi 'empty description' "$TMP/err.i"; then
  ok "(i) user row with empty description fails --check"
else
  fail "(i) stderr did not report empty description on SYG_ALPHA: $(cat "$TMP/err.i")"
fi
write_valid_tsv

# (j) Row with an empty default -> --check fails.
sed -i $'s/^SYG_ALPHA\tuser\tguards\t1\t/SYG_ALPHA\tuser\tguards\t\t/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.j"; then
  fail "(j) --check passed despite empty default on SYG_ALPHA"
elif grep -q 'SYG_ALPHA' "$TMP/err.j" && grep -qi 'empty default' "$TMP/err.j"; then
  ok "(j) row with empty default fails --check"
else
  fail "(j) stderr did not report empty default on SYG_ALPHA: $(cat "$TMP/err.j")"
fi
write_valid_tsv

# (k) Row with 4 fields -> --check fails.
sed -i $'s/^SYG_ALPHA\t.*/SYG_ALPHA\tuser\tguards\t1/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.k"; then
  fail "(k) --check passed despite 4-field row on SYG_ALPHA"
elif grep -q 'SYG_ALPHA' "$TMP/err.k" && grep -q '4 fields' "$TMP/err.k"; then
  ok "(k) row with 4 fields fails --check"
else
  fail "(k) stderr did not report 4 fields on SYG_ALPHA: $(cat "$TMP/err.k")"
fi
write_valid_tsv

# (l) Description of 221 characters -> --check fails.
DESC_221="$(printf '%*s' 221 '' | tr ' ' 'x')"
sed -i $'s/^SYG_ALPHA\t.*/SYG_ALPHA\tuser\tguards\t1\t'"$DESC_221"$'/' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.l"; then
  fail "(l) --check passed despite 221-character description on SYG_ALPHA"
elif grep -q 'SYG_ALPHA' "$TMP/err.l" && grep -q '221 chars' "$TMP/err.l"; then
  ok "(l) description of 221 characters fails --check"
else
  fail "(l) stderr did not report 221-character description on SYG_ALPHA: $(cat "$TMP/err.l")"
fi
write_valid_tsv

# (m) knobs.tsv itself is not scanned when a row description mentions SYG_KILO.
sed -i $'s/^SYG_ALPHA\t.*/SYG_ALPHA\tuser\tguards\t1\tControls alpha guard alongside SYG_KILO./' "$TMP/plugins/seyag/config/knobs.tsv"
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.m.w"; then
  fail "(m) --write failed when knobs.tsv description mentioned SYG_KILO: $(cat "$TMP/err.m.w")"
elif python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.m"; then
  ok "(m) knobs.tsv itself is not scanned when a row description mentions SYG_KILO"
else
  fail "(m) --check failed when knobs.tsv description mentioned SYG_KILO: $(cat "$TMP/err.m")"
fi
write_valid_tsv
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.m.restore"; then
  fail "(m) restoring docs/config.md with --write failed: $(cat "$TMP/err.m.restore")"
fi

# (n) Non-UTF-8 file under plugins/seyag/bin containing SYG_LIMA is scanned with replacement
# characters: SYG_LIMA is found (a missing row fails) and a warning names the file; a row passes.
printf 'SYG_LIMA\xff\n' >"$TMP/plugins/seyag/bin/non-utf8-bin"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.n1"; then
  fail "(n) --check passed with SYG_LIMA in a non-UTF-8 file and no knobs row"
elif grep -q 'SYG_LIMA read by' "$TMP/err.n1" && grep -q 'bin/non-utf8-bin is not valid UTF-8' "$TMP/err.n1"; then
  ok "(n) SYG_LIMA in a non-UTF-8 file is found (no row fails) and the file is warned about"
else
  fail "(n) stderr did not name SYG_LIMA with its warning: $(cat "$TMP/err.n1")"
fi
printf 'SYG_LIMA\tuser\tmisc\tunset\tFixture row for a name in a non-UTF-8 file.\n' >>"$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.n2" && python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.n3"; then
  if grep -q 'bin/non-utf8-bin is not valid UTF-8' "$TMP/err.n3"; then
    ok "(n) with a knobs row for SYG_LIMA the check passes and the warning still prints"
  else
    fail "(n) warning missing on the passing run: $(cat "$TMP/err.n3")"
  fi
else
  fail "(n) check failed with a knobs row for SYG_LIMA: $(cat "$TMP/err.n2" "$TMP/err.n3" 2>/dev/null)"
fi
rm -f "$TMP/plugins/seyag/bin/non-utf8-bin"
write_valid_tsv
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.n.restore"; then
  fail "(n) restoring docs/config.md with --write failed: $(cat "$TMP/err.n.restore")"
fi

# (o) CRLF-converted docs/config.md -> --check fails.
sed -i 's/$/\r/' "$TMP/docs/config.md"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.o"; then
  fail "(o) --check passed despite CRLF-converted docs/config.md"
elif grep -q 'docs/config.md' "$TMP/err.o"; then
  ok "(o) CRLF-converted docs/config.md fails --check"
else
  fail "(o) stderr did not name docs/config.md on CRLF doc: $(cat "$TMP/err.o")"
fi
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.o.restore"; then
  fail "(o) restoring docs/config.md with --write failed: $(cat "$TMP/err.o.restore")"
fi

# (p) A prose: default renders as plain text: no backticks, no prefix, its | escaped.
sed -i $'s/^SYG_ALPHA\t.*/SYG_ALPHA\tuser\tguards\tprose:Plain a|b words\tControls alpha guard mode (0|1)./' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.p" && grep -qF '| `SYG_ALPHA` | Plain a\|b words |' "$TMP/docs/config.md" && ! grep -qF '`Plain a' "$TMP/docs/config.md"; then
  ok "(p) prose: default renders as plain text without backticks or the prefix, | escaped"
else
  fail "(p) prose: default did not render as plain text: $(cat "$TMP/err.p")"
fi
write_valid_tsv
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.p.restore"; then
  fail "(p) restoring docs/config.md with --write failed: $(cat "$TMP/err.p.restore")"
fi

# (q) A bare prose: default (empty remainder after the prefix) fails validation.
sed -i $'s/^SYG_ALPHA\t.*/SYG_ALPHA\tuser\tguards\tprose:\tControls alpha guard mode (0|1)./' "$TMP/plugins/seyag/config/knobs.tsv"
if python3 "$SCRIPT" --root "$TMP" --check 2>"$TMP/err.q"; then
  fail "(q) --check passed with a bare prose: default"
elif grep -q 'SYG_ALPHA in knobs.tsv' "$TMP/err.q" && grep -q 'has empty prose default' "$TMP/err.q"; then
  ok "(q) bare prose: default fails validation naming SYG_ALPHA"
else
  fail "(q) stderr did not name SYG_ALPHA's empty prose default: $(cat "$TMP/err.q")"
fi
write_valid_tsv
if ! python3 "$SCRIPT" --root "$TMP" --write 2>"$TMP/err.q.restore"; then
  fail "(q) restoring docs/config.md with --write failed: $(cat "$TMP/err.q.restore")"
fi

# Live check against the repository root.
if python3 "$SCRIPT" --root "$REPO_ROOT" --check 2>"$TMP/err.live"; then
  ok "(live) repo knobs.tsv and docs/config.md are valid and in sync"
else
  fail "(live) repo check failed: $(cat "$TMP/err.live")"
fi

echo ""
if [ "$FAILURES" -gt 0 ]; then
  echo "FAILED ($FAILURES failure(s))"
  exit 1
fi
echo "ALL PASSED"
exit 0
